package delivery

import (
	"bytes"
	"crypto/rand"
	"crypto/rsa"
	"crypto/x509"
	"encoding/base64"
	"encoding/hex"
	"encoding/json"
	"os"
	"path/filepath"
	"testing"
)

type deliveryVector struct {
	RSAPrivatePKCS8DERB64 string `json:"rsa_private_pkcs8_der_b64"`
	KEKID                 string `json:"kek_id"`
	Version               int    `json:"version"`
	NonceB64              string `json:"nonce_b64"`
	WrappedKEK            string `json:"wrapped_kek"`
	KEKHex                string `json:"kek_hex"`
	Note                  string `json:"note"`
}

func TestWriteVector(t *testing.T) {
	path := os.Getenv("TPM_MSK_WRITE_VECTOR")
	if path == "" {
		t.Skip("TPM_MSK_WRITE_VECTOR is empty")
	}

	priv, err := rsa.GenerateKey(rand.Reader, 3072)
	if err != nil {
		t.Fatal(err)
	}
	kek := make([]byte, 32)
	nonce := make([]byte, 32)
	for i := range kek {
		kek[i] = byte(i)
		nonce[i] = byte(i + 0x20)
	}
	wrapped, err := Wrap(&priv.PublicKey, kek, "kek-01", 3, nonce)
	if err != nil {
		t.Fatal(err)
	}
	der, err := x509.MarshalPKCS8PrivateKey(priv)
	if err != nil {
		t.Fatal(err)
	}
	vector := deliveryVector{
		RSAPrivatePKCS8DERB64: base64.StdEncoding.EncodeToString(der),
		KEKID:                 "kek-01",
		Version:               3,
		NonceB64:              base64.StdEncoding.EncodeToString(nonce),
		WrappedKEK:            base64.StdEncoding.EncodeToString(wrapped),
		KEKHex:                hex.EncodeToString(kek),
		Note:                  "test-only RSA-3072 private key generated by TestWriteVector; not a secret, do not use in production",
	}
	data, err := json.MarshalIndent(vector, "", "  ")
	if err != nil {
		t.Fatal(err)
	}
	if err := os.MkdirAll(filepath.Dir(path), 0755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, append(data, '\n'), 0600); err != nil {
		t.Fatal(err)
	}
}

func TestDeliveryVectorUnwrap(t *testing.T) {
	path := filepath.Join("..", "..", "..", "key-container", "testdata", "delivery_vector.json")
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	var vector deliveryVector
	if err := json.Unmarshal(data, &vector); err != nil {
		t.Fatal(err)
	}
	der, err := base64.StdEncoding.DecodeString(vector.RSAPrivatePKCS8DERB64)
	if err != nil {
		t.Fatal(err)
	}
	parsed, err := x509.ParsePKCS8PrivateKey(der)
	if err != nil {
		t.Fatal(err)
	}
	priv, ok := parsed.(*rsa.PrivateKey)
	if !ok {
		t.Fatal("PKCS#8 key is not RSA")
	}
	wrapped, err := base64.StdEncoding.DecodeString(vector.WrappedKEK)
	if err != nil {
		t.Fatal(err)
	}
	nonce, err := base64.StdEncoding.DecodeString(vector.NonceB64)
	if err != nil {
		t.Fatal(err)
	}
	want, err := hex.DecodeString(vector.KEKHex)
	if err != nil {
		t.Fatal(err)
	}
	got, err := Unwrap(priv, wrapped, vector.KEKID, vector.Version, nonce)
	if err != nil {
		t.Fatal(err)
	}
	defer clear(got)
	if !bytes.Equal(got, want) {
		t.Fatal("unwrapped KEK does not match vector")
	}
}
